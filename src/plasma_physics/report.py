"""Run every analysis and write reports/results.md and reports/figures/*.png.

Usage: uv run python -m plasma_physics.report
"""

from dataclasses import dataclass
from pathlib import Path

import matplotlib
import matplotlib.ticker

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from scipy.stats import spearmanr  # noqa: E402

from plasma_physics.coherence import permutation_test, segment_spectra  # noqa: E402
from plasma_physics.io import (  # noqa: E402
    TimeSeries,
    load_density,
    load_efield,
    load_legacy_slopes,
    load_selected_slopes,
)
from plasma_physics.legacy import legacy_all  # noqa: E402
from plasma_physics.spectral import FIT_BAND_HZ, hann_periodogram, loglog_fit  # noqa: E402
from plasma_physics.spikes import clean_segments, detect_spikes  # noqa: E402
from plasma_physics.stats import block_bootstrap_ci  # noqa: E402

REPORTS = Path(__file__).resolve().parents[2] / "reports"
SEED = 42
N_PERM = 2000
BLOCK_SEGMENTS = 30  # ~28 s of flight per coherence block
SUB = 0.75  # seconds per sub-window (same as 2022)
PERIODS = [(260, 400), (400, 500), (500, 815), (815, 900)]
MAIN_PERIOD = (500, 815)  # the period analysed in 2022

# Chart tokens (reference palette from the dataviz guide, light mode)
SURFACE, INK, INK_2, MUTED, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#898781", "#e1e0d9"
BLUE, ORANGE = "#2a78d6", "#eb6834"


@dataclass
class Window:
    t0: float
    t1: float
    slope_n: float
    slope_e: float


def mean_se(x: np.ndarray) -> tuple[float, float]:
    return float(np.mean(x)), float(np.std(x, ddof=1) / np.sqrt(len(x)))


def pair_slopes(
    density: TimeSeries, efield: TimeSeries, subwindows: list[tuple[float, float]], band
) -> tuple[float, float]:
    """Slopes of the averaged spectra of several 0.75 s sub-windows (density and E alike)."""
    pn, pe = [], []
    for a, _ in subwindows:
        dn = density.x[(density.t >= a) & (density.t < a + SUB)]
        de = efield.x[(efield.t >= a) & (efield.t < a + SUB)]
        n_n, n_e = int(SUB * density.fs), int(SUB * efield.fs)
        fn, p = hann_periodogram(dn[:n_n], density.fs)
        fe, q = hann_periodogram(de[:n_e], efield.fs)
        pn.append(p)
        pe.append(q)
    s_n = loglog_fit(fn, np.mean(pn, axis=0), band).slope
    s_e = loglog_fit(fe, np.mean(pe, axis=0), band).slope
    return s_n, s_e


def style(ax: plt.Axes) -> None:
    ax.set_facecolor(SURFACE)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(MUTED)
    ax.tick_params(colors=INK_2, labelsize=9)
    ax.grid(True, color=GRID, lw=0.6)
    ax.set_axisbelow(True)


def new_fig(*args, **kwargs):
    fig, ax = plt.subplots(*args, **kwargs)
    fig.patch.set_facecolor(SURFACE)
    for a in np.atleast_1d(ax):
        style(a)
    return fig, ax


def main() -> None:
    rng = np.random.default_rng(SEED)
    fig_dir = REPORTS / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    density, efield = load_density(), load_efield()
    lines: list[str] = ["# Results", "", "Generated by `make reproduce`. Do not edit by hand.", ""]

    # 1. Reproduction of the 2022 MATLAB numbers ------------------------------------------
    ref = load_legacy_slopes()
    mine = legacy_all(density, efield)

    def key(row: np.ndarray) -> tuple[float, float]:  # a window is identified by its times
        return round(row[2], 2), round(row[3], 2)

    lookup = {key(r): r[:2] for r in mine}
    diffs = np.array([lookup[key(r)] - r[:2] for r in ref])
    lines += [
        "## 1. Reproduction of the 2022 MATLAB analysis",
        "",
        f"- Windows reproduced: {len(diffs)} of {len(ref)}; "
        f"max absolute slope difference {np.abs(diffs).max():.1e}.",
        "",
    ]

    # 2. The 2022 result, and how robust it is ----------------------------------------------
    sel = load_selected_slopes()
    d_sel = sel[:, 1] - sel[:, 0]
    d_all = ref[:, 1] - ref[:, 0]
    m_sel, se_sel = mean_se(d_sel)
    m_all, se_all = mean_se(d_all)
    lines += [
        "## 2. The 2022 result (fit band 10-40 Hz)",
        "",
        "| Windows | N | Density slope | E-field slope | E minus density | Corr. of slopes |",
        "|---|---|---|---|---|---|",
        f"| Hand-selected | {len(sel)} | {sel[:, 0].mean():.2f} | {sel[:, 1].mean():.2f} | "
        f"{m_sel:.2f} ± {se_sel:.2f} | {np.corrcoef(sel[:, 0], sel[:, 1])[0, 1]:.2f} |",
        f"| All computed | {len(ref)} | {ref[:, 0].mean():.2f} | {ref[:, 1].mean():.2f} | "
        f"{m_all:.2f} ± {se_all:.2f} | {np.corrcoef(ref[:, 0], ref[:, 1])[0, 1]:.2f} |",
        "",
        "Sensitivity of E minus density on the 64 hand-selected windows "
        "(detrended spectra, same sub-windows):",
        "",
        "| Fit band (Hz) | E minus density (mean ± s.e.) |",
        "|---|---|",
    ]
    for band in [(5.0, 20.0), FIT_BAND_HZ, (10.0, 60.0), (20.0, 60.0)]:
        d = []
        for t0, t1 in sel[:, 2:4]:
            s_n, s_e = pair_slopes(density, efield, [(t0, 0), (t1 - SUB, 0)], band)
            d.append(s_e - s_n)
        m, se = mean_se(np.array(d))
        lines.append(f"| {band[0]:.0f} to {band[1]:.0f} | {m:.2f} ± {se:.2f} |")
    lines.append("")

    # 3. Automatic windows over the whole flight --------------------------------------------
    spikes = detect_spikes(efield)
    segs = clean_segments(spikes)
    in_range = (segs.start > density.t[0]) & (segs.start + SUB < efield.t[-1])
    starts = segs.start[in_range]
    windows: list[Window] = []
    for a, b in zip(starts[:-1], starts[1:], strict=True):
        if b - a < 1.0:  # consecutive half spins only, as in 2022
            s_n, s_e = pair_slopes(density, efield, [(a, 0), (b, 0)], FIT_BAND_HZ)
            windows.append(Window(a, b + SUB, s_n, s_e))
    windows = windows[::2]  # non-overlapping pairs
    t_win = np.array([w.t0 for w in windows])
    sn = np.array([w.slope_n for w in windows])
    se_ = np.array([w.slope_e for w in windows])
    lines += [
        "## 3. Automatic windows (sun spikes detected, whole flight)",
        "",
        f"- Spikes detected: {len(spikes.start)}; median spacing "
        f"{np.median(np.diff(spikes.start)):.3f} s.",
        f"- Clean segments (0.75 to 0.9 s between spikes): {len(segs.start)}.",
        f"- Windows (pairs of consecutive segments): {len(windows)}, "
        f"from {windows[0].t0:.0f} s to {windows[-1].t1:.0f} s.",
        "",
        "| Flight period (s) | Windows | Density slope | E-field slope | E minus density |",
        "|---|---|---|---|---|",
    ]
    for a, b in PERIODS:
        m = (t_win >= a) & (t_win < b)
        lines.append(
            f"| {a} to {b} | {m.sum()} | {sn[m].mean():.2f} | {se_[m].mean():.2f} | "
            f"{np.mean(se_[m] - sn[m]):.2f} |"
        )
    # A density slope near 0 means a flat spectrum: the traced density is at its noise floor
    # in 10-40 Hz, so the comparison is only meaningful in the main period.
    main_m = (t_win >= MAIN_PERIOD[0]) & (t_win < MAIN_PERIOD[1])
    d_auto = se_[main_m] - sn[main_m]
    lo, hi = block_bootstrap_ci(d_auto, block=10, n_boot=5000, rng=rng)
    lines += [
        "",
        f"Main period ({MAIN_PERIOD[0]} to {MAIN_PERIOD[1]} s, where the density spectrum is "
        f"not flat): E minus density = {d_auto.mean():.2f}, 95% CI [{lo:.2f}, {hi:.2f}] "
        "(moving-block bootstrap, blocks of 10 windows).",
        "",
    ]

    # 4. Coherence -------------------------------------------------------------------------
    spec = segment_spectra(density, efield, segs)
    band = (spec.f >= FIT_BAND_HZ[0]) & (spec.f <= FIT_BAND_HZ[1])
    raw = segment_spectra(density, efield, segs, sign_correct=False)
    c_raw, p_raw, _ = permutation_test(raw.X, raw.Y, band, N_PERM, rng)
    c_all, p_all, null_all = permutation_test(spec.X, spec.Y, band, N_PERM, rng)
    n_blocks = len(spec.t) // BLOCK_SEGMENTS
    alpha_bonf = 0.05 / n_blocks
    blocks = []
    for k in range(n_blocks):
        s = slice(k * BLOCK_SEGMENTS, (k + 1) * BLOCK_SEGMENTS)
        c, p, null = permutation_test(spec.X[s], spec.Y[s], band, N_PERM, rng)
        blocks.append((spec.t[s][0], spec.t[s][-1] + SUB, c, float(np.quantile(null, 0.95)), p))
    n_sig = sum(p < alpha_bonf for *_, p in blocks)
    lines += [
        "## 4. Coherence between density and E field (10-40 Hz)",
        "",
        f"- Segments: {len(spec.t)}; permutations: {N_PERM}.",
        f"- Without sign correction: coherence {c_raw:.4f}, p = {p_raw:.3f}.",
        f"- With sign correction: coherence {c_all:.4f} "
        f"(null mean {null_all.mean():.4f}), p = {p_all:.4f}.",
        f"- Blocks of {BLOCK_SEGMENTS} segments: {n_sig} of {n_blocks} significant after "
        f"Bonferroni (p < {alpha_bonf:.4f}).",
        "",
        "| Block (s) | Coherence | Null 95th pct. | p-value |",
        "|---|---|---|---|",
    ]
    lines += [
        f"| {a:.0f} to {b:.0f} | {c:.3f} | {q:.3f} | {p:.4f}{' *' if p < alpha_bonf else ''} |"
        for a, b, c, q, p in blocks
    ]
    lines.append("")

    # 5. Exploratory: does coherence follow signal strength? ------------------------------
    # Density power at 60-75 Hz is used as its noise floor (the spectrum is flat there).
    floor = (spec.f >= 60) & (spec.f <= 75)
    strength = []
    for k in range(n_blocks):
        s = slice(k * BLOCK_SEGMENTS, (k + 1) * BLOCK_SEGMENTS)
        pn = (np.abs(spec.X[s]) ** 2).mean(axis=0)
        pe = (np.abs(spec.Y[s]) ** 2).mean(axis=0)
        strength.append((pn[band].mean() / pn[floor].mean(), pe[band].mean()))
    strength = np.array(strength)
    coh = np.array([c for _, _, c, _, _ in blocks])
    rho_e, p_e = spearmanr(coh, strength[:, 1])
    rho_n, p_n = spearmanr(coh, strength[:, 0])
    lines += [
        "## 5. Exploratory: coherence and signal strength",
        "",
        "The significant blocks sit where the rocket appears to be inside the aurora. Per block:",
        "",
        f"- Coherence vs E-field power in 10-40 Hz: Spearman rho = {rho_e:.2f}, p = {p_e:.3f}.",
        f"- Coherence vs density signal-to-noise (power 10-40 Hz / 60-75 Hz): "
        f"rho = {rho_n:.2f}, p = {p_n:.3f}.",
        "",
        "| Block (s) | Coherence | Density signal-to-noise | E-field power (counts², rel.) |",
        "|---|---|---|---|",
    ]
    e_ref = strength[:, 1].min()
    lines += [
        f"| {a:.0f} to {b:.0f} | {c:.3f} | {sn_:.1f} | {pe_ / e_ref:.0f} |"
        for (a, b, c, _, _), (sn_, pe_) in zip(blocks, strength, strict=True)
    ]
    lines += [
        "",
        "Two readings fit this pattern: the coupling is physically stronger inside the aurora, "
        "or it is only detectable when both signals are strong (a density signal-to-noise near "
        "1 means the density is pure noise in that band). These data cannot separate them; a "
        "cleaner density trace or an independent auroral marker (particle data) could. "
        "With 14 blocks and no pre-registered hypothesis, treat this as exploratory.",
        "",
    ]
    (REPORTS / "results.md").write_text("\n".join(lines))

    # Figures ------------------------------------------------------------------------------
    plot_coherence(blocks, alpha_bonf, fig_dir / "coherence_blocks.png")
    main_starts = segs.start[in_range]
    main_starts = main_starts[(main_starts >= MAIN_PERIOD[0]) & (main_starts < MAIN_PERIOD[1])]
    plot_spectra(density, efield, main_starts, fig_dir / "mean_spectra.png")
    plot_slope_diff(d_auto, (lo, hi), fig_dir / "slope_difference.png")
    plot_spikes(efield, spikes, segs, fig_dir / "efield_spikes.png")
    plot_strength(blocks, strength[:, 1] / e_ref, alpha_bonf, fig_dir / "coherence_vs_power.png")
    print("\n".join(lines))


def plot_strength(blocks, e_power, alpha_bonf, path: Path) -> None:
    fig, ax = new_fig(figsize=(6.5, 3.8))
    for (_, _, c, _, p), x in zip(blocks, e_power, strict=True):
        sig = p < alpha_bonf
        ax.plot(x, c, "o", ms=8, mfc=BLUE if sig else SURFACE, mec=BLUE, mew=2)
    ax.plot([], [], "o", ms=8, mfc=BLUE, mec=BLUE, label="significant (Bonferroni)")
    ax.plot([], [], "o", ms=8, mfc=SURFACE, mec=BLUE, mew=2, label="not significant")
    ax.set_xscale("log")
    ax.set_xlabel("E-field power in 10-40 Hz (relative to the quietest block)", color=INK_2)
    ax.set_ylabel("Coherence, 10-40 Hz", color=INK_2)
    ax.set_title("Coherence rises with wave activity", loc="left", color=INK, fontsize=11)
    ax.legend(frameon=False, fontsize=9, labelcolor=INK_2, loc="upper left")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_coherence(blocks, alpha_bonf, path: Path) -> None:
    fig, ax = new_fig(figsize=(9, 3.8))
    for a, b, c, q, p in blocks:
        mid = (a + b) / 2
        ax.fill_between([a, b], 0, q, color=GRID, lw=0)
        sig = p < alpha_bonf
        ax.plot(mid, c, "o", ms=8, mfc=BLUE if sig else SURFACE, mec=BLUE, mew=2, zorder=3)
    ax.plot([], [], "o", ms=8, mfc=BLUE, mec=BLUE, label="significant (Bonferroni)")
    ax.plot([], [], "o", ms=8, mfc=SURFACE, mec=BLUE, mew=2, label="not significant")
    ax.fill_between([], [], color=GRID, label="95% of shuffled pairings")
    ax.set_xlabel("Flight time (s)", color=INK_2)
    ax.set_ylabel("Coherence, 10-40 Hz", color=INK_2)
    ax.set_ylim(0, None)
    ax.set_title(
        "Density and E field are coherent only in some stretches of the flight",
        loc="left",
        color=INK,
        fontsize=11,
    )
    ax.legend(frameon=False, fontsize=9, labelcolor=INK_2, loc="upper left")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_spectra(density: TimeSeries, efield: TimeSeries, starts, path: Path) -> None:
    fig, axes = new_fig(1, 2, figsize=(10, 3.8))
    for ax, ts, color, name in [
        (axes[0], density, BLUE, "Density (relative)"),
        (axes[1], efield, ORANGE, "E field (raw counts)"),
    ]:
        n = int(SUB * ts.fs)
        ps = []
        for a in starts:
            x = ts.x[(ts.t >= a) & (ts.t < a + SUB)][:n]
            if len(x) == n:
                f, p = hann_periodogram(x / np.mean(x) if ts is density else x, ts.fs)
                ps.append(p)
        p = np.exp(np.mean(np.log(np.array(ps)[:, 1:]), axis=0))  # geometric mean
        f = f[1:]
        fit = loglog_fit(f, p)
        ax.axvspan(*FIT_BAND_HZ, color=GRID, lw=0)
        ax.loglog(f, p, color=color, lw=2)
        ax.set_title(
            f"{name}: slope {fit.slope:.2f} in 10-40 Hz", loc="left", color=INK, fontsize=10
        )
        ax.set_xlabel("Frequency (Hz)", color=INK_2)
        ax.xaxis.set_minor_formatter(matplotlib.ticker.NullFormatter())
    axes[0].set_ylabel("Power (arbitrary units)", color=INK_2)
    fig.suptitle(
        f"Mean spectra of clean segments, {MAIN_PERIOD[0]} to {MAIN_PERIOD[1]} s "
        "(shaded: fit band)",
        x=0.01,
        ha="left",
        color=INK_2,
        fontsize=9,
    )
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_slope_diff(d: np.ndarray, ci: tuple[float, float], path: Path) -> None:
    fig, ax = new_fig(figsize=(7, 3.6))
    ax.hist(d, bins=30, color=BLUE, edgecolor=SURFACE, lw=1)
    ax.axvspan(*ci, color=INK_2, alpha=0.15, lw=0)
    ax.axvline(np.mean(d), color=INK, lw=2)
    ax.axvline(2, color=MUTED, lw=2, ls="--")
    top = ax.get_ylim()[1]
    ax.text(
        np.mean(d), top * 0.95, f"  observed mean {np.mean(d):.2f}", color=INK, fontsize=9, va="top"
    )
    ax.text(
        2,
        top * 0.80,
        "  +2 (2022 working\n  expectation)",
        color=INK_2,
        fontsize=9,
        va="top",
    )
    ax.set_xlabel(
        f"E-field slope minus density slope, per window ({MAIN_PERIOD[0]} to {MAIN_PERIOD[1]} s)",
        color=INK_2,
    )
    ax.set_ylabel("Windows", color=INK_2)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def plot_spikes(
    efield: TimeSeries, spikes, segs, path: Path, t0: float = 528.0, t1: float = 534.0
) -> None:
    fig, ax = new_fig(figsize=(9, 3.2))
    m = (efield.t >= t0) & (efield.t <= t1)
    for a, b in zip(segs.start, segs.end, strict=True):
        if a < t1 and b > t0:
            ax.axvspan(max(a, t0), min(b, t1), color=BLUE, alpha=0.12, lw=0)
    for a, b in zip(spikes.start, spikes.end, strict=True):
        if t0 <= a <= t1:
            ax.axvspan(a - 0.01, b + 0.01, color=ORANGE, alpha=0.35, lw=0)
    ax.plot(efield.t[m], efield.x[m], color=INK_2, lw=0.8)
    ax.axvspan(0, 0, color=BLUE, alpha=0.12, label="clean segment used")
    ax.axvspan(0, 0, color=ORANGE, alpha=0.35, label="detected sun spike")
    ax.set_xlim(t0, t1)
    ax.set_xlabel("Flight time (s)", color=INK_2)
    ax.set_ylabel("E field (raw counts)", color=INK_2)
    ax.legend(
        frameon=False,
        fontsize=9,
        labelcolor=INK_2,
        loc="lower left",
        bbox_to_anchor=(0, 1.0),
        ncols=2,
    )
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


if __name__ == "__main__":
    main()
